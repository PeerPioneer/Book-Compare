'use strict';
/* Builds ../../app/js/align-worker.js from the research modules (so that the app runs exactly the code that was tested in Node.js).
   usage: node build_worker.js            (writes the file)
          node build_worker.js --check    (fails if the committed file is out of date)  */
const fs = require('fs'), path = require('path');
const MODULES = ['rectmorph', 'printed_area', 'rough_align', 'tile_align', 'pipeline', 'movement'];
const out = path.join(__dirname, '..', '..', 'app', 'js', 'align-worker.js');
let code = '/* Book Compare: alignment worker. GENERATED by research/js/build_worker.js from the research modules; do not edit by hand.\n' +
  '   Runs the printed-area detection, rough alignment and tile alignment off the main thread, using OpenCV.js (Apache-2.0). */\n' +
  '(function () {\n\'use strict\';\nvar __defs = {}, __cache = {};\n' +
  'function require(name) { name = name.replace(/^\\.\\//, \'\').replace(/\\.js$/, \'\'); if (name === \'./printed_area\') name = \'printed_area\';\n' +
  '  if (__cache[name]) return __cache[name].exports; var m = __cache[name] = { exports: {} }; if (!__defs[name]) throw new Error(\'no module \' + name); __defs[name](m, m.exports, require); return m.exports; }\n';
for (const name of MODULES) {
  const src = fs.readFileSync(path.join(__dirname, name + '.js'), 'utf8').replace(/^'use strict';\n/, '');
  code += `__defs[${JSON.stringify(name)}] = function (module, exports, require) {\n${src}\n};\n`;
}
code += fs.readFileSync(path.join(__dirname, 'worker_main.js'), 'utf8') + '\n})();\n';
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== code) { console.error('app/js/align-worker.js is out of date: run  node research/js/build_worker.js'); process.exit(1); }
  console.log('align-worker.js is up to date');
} else { fs.writeFileSync(out, code); console.log('wrote', out, (code.length / 1024).toFixed(0) + ' KB'); }
